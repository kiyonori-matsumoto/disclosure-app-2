import 'package:disclosure_app_fl/app.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('App Material 3 Theme Tests', () {
    test('buildLightTheme uses Material 3 and light ColorScheme', () {
      final theme = buildLightTheme();
      expect(theme.useMaterial3, isTrue);
      expect(theme.colorScheme.brightness, equals(Brightness.light));
      // Light primary should be dark deep purple
      expect(theme.colorScheme.primary, isNotNull);
    });

    test('buildDarkTheme uses Material 3 and high-contrast dark ColorScheme', () {
      final darkTheme = buildDarkTheme();
      expect(darkTheme.useMaterial3, isTrue);
      expect(darkTheme.colorScheme.brightness, equals(Brightness.dark));
      expect(darkTheme.colorScheme.primary, isNotNull);
      // Dark primary should be light lavender generated by ColorScheme.fromSeed, not dark purple
      final hsl = HSLColor.fromColor(darkTheme.colorScheme.primary);
      expect(hsl.lightness, greaterThan(0.6));
      expect(darkTheme.colorScheme.primaryContainer, isNotNull);
      expect(darkTheme.colorScheme.onPrimaryContainer, isNotNull);
    });
  });
}
